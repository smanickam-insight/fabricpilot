"""
ADF Error Analytics - Log Analytics dashboard.

Data source cascade (when using Live mode):
    Signed-in identity -> Subscription -> Log Analytics Workspace -> KQL query -> Analysis

Falls back to synthetic Demo Data when the user hasn't signed in / prefers a
no-Azure-connection walkthrough (e.g. for client demos).

Remediation steps are generated by an LLM from the *actual* error text of each
recurring failure (services.llm_remediation). The static PLAYBOOKS in
services.remediation are used only as a fallback when no provider is configured
or a call fails.
"""

import pandas as pd
import streamlit as st

from services.alerting import dispatch_escalations, find_escalations, ESCALATION_MIN_DAYS
from services.azure_api import list_subscriptions, list_log_analytics_workspaces, run_kql_query
from services.analytics import generate_demo_data, build_kql_query, analyze, Analysis
from services.redaction import redact_text
from services.remediation import (
    build_remediation_plan, plan_summary_df, plan_to_markdown, plan_to_csv,
)
from services.llm_remediation import clear_cache, llm_enabled, provider_label


def _secret(key: str, default: str = "") -> str:
    """Safe access to st.secrets: never raises if secrets.toml is absent."""
    try:
        return st.secrets.get(key, default)
    except Exception:  # noqa: BLE001
        return default


def _get_subscriptions():
    if "law_subscriptions" not in st.session_state:
        with st.spinner("Resolving subscriptions..."):
            result = list_subscriptions()
            if result.get("error"):
                st.sidebar.error(f"Failed to load subscriptions: {result['error']}")
                return []
            st.session_state.law_subscriptions = sorted(
                result.get("value", []), key=lambda s: (s.get("displayName") or "").lower()
            )
    return st.session_state.law_subscriptions


def _get_workspaces(subscription_id: str):
    cache = st.session_state.setdefault("law_workspaces_cache", {})
    if subscription_id not in cache:
        with st.spinner("Resolving Log Analytics workspaces..."):
            result = list_log_analytics_workspaces(subscription_id)
            if result.get("error"):
                st.sidebar.error(f"Failed to load workspaces: {result['error']}")
                return []
            cache[subscription_id] = sorted(
                result.get("value", []), key=lambda w: (w.get("name") or "").lower()
            )
    return cache[subscription_id]


def render_dashboard_section():
    # ========================================================================
    # SIDEBAR — Subscription · Workspace · Window
    # ========================================================================
    st.sidebar.markdown("### ⚙️ Subscription · Workspace · Window")

    is_authenticated = bool(st.session_state.get("authenticated"))

    data_source = st.sidebar.radio(
        "Data source",
        ["Demo Data", "Live Azure Log Analytics"],
        index=0 if not is_authenticated else 1,
        help="Demo Data works instantly with no Azure connection. Live mode requires "
             "signing in on the Authentication tab and pulls real ADF failure logs.",
    )

    workspace_customer_id = None
    subscription_label = "Demo Subscription"
    workspace_label = "Demo Workspace"

    if data_source == "Live Azure Log Analytics":
        if not is_authenticated:
            st.sidebar.warning("⚠️ Please sign in from the **🔐 Authentication** tab first.")
        else:
            subs = _get_subscriptions()
            if subs:
                sub_display = {
                    f"{s.get('displayName')} ({s.get('subscriptionId')})": s.get("subscriptionId")
                    for s in subs
                }
                sub_choice = st.sidebar.selectbox("Azure Subscription", list(sub_display.keys()))
                subscription_id = sub_display[sub_choice]
                subscription_label = sub_choice

                workspaces = _get_workspaces(subscription_id)
                if workspaces:
                    ws_display = {
                        f"{w.get('name')} · {w.get('id','').split('/resourceGroups/')[-1].split('/')[0]} "
                        f"({w.get('location')})": w
                        for w in workspaces
                    }
                    ws_choice = st.sidebar.selectbox("Log Analytics Workspace", list(ws_display.keys()))
                    selected_ws = ws_display[ws_choice]
                    workspace_customer_id = selected_ws.get("properties", {}).get("customerId")
                    workspace_label = ws_choice
                    st.sidebar.caption(f"Workspace ID (GUID): `{workspace_customer_id}`")
                else:
                    st.sidebar.info("No Log Analytics workspaces found in this subscription.")
            else:
                st.sidebar.info("No subscriptions found for the signed-in account.")

            if st.sidebar.button("🔄 Reload subscriptions / workspaces"):
                for key in ("law_subscriptions", "law_workspaces_cache"):
                    st.session_state.pop(key, None)
                st.rerun()

    lookback_days = st.sidebar.selectbox(
        "Lookback", [1, 3, 7, 14, 30, 45, 60, 75, 90], index=2, format_func=lambda d: f"{d} Days"
    )
    run_clicked = st.sidebar.button("🔍 Run Analysis", width='stretch', type="primary")

    st.sidebar.markdown("---")
    alert_threshold = st.sidebar.number_input("🔔 Alert if today's failures ≥", min_value=1, value=5, step=1)
    show_raw = st.sidebar.checkbox(
        "Show raw error text (unredacted)", value=False,
        help="Off by default. Error messages are redacted for secrets (connection strings, "
             "SAS tokens, auth headers) before display. Turn on only when it's safe to show raw text.",
    )

    # ========================================================================
    # RUN ANALYSIS
    # ========================================================================
    if "analysis" not in st.session_state:
        st.session_state.analysis = None

    if run_clicked:
        with st.spinner("Running analysis..."):
            try:
                if data_source == "Demo Data":
                    raw_df = generate_demo_data(lookback_days)
                else:
                    if not workspace_customer_id:
                        st.sidebar.error("Select a Subscription and Log Analytics Workspace first.")
                        raw_df = None
                    else:
                        query = build_kql_query(lookback_days)
                        result = run_kql_query(workspace_customer_id, query)
                        if result.get("error"):
                            st.sidebar.error(f"KQL query failed: {result['error']}")
                            raw_df = None
                        else:
                            raw_df = pd.DataFrame(result.get("value", []))

                if raw_df is not None and len(raw_df) > 0:
                    st.session_state.analysis = analyze(raw_df)
                elif raw_df is not None:
                    st.sidebar.info("Query succeeded but returned zero failed activities in this window.")
            except Exception as e:
                st.sidebar.error(f"Analysis failed: {redact_text(str(e))}")

    # ========================================================================
    # HEADER
    # ========================================================================
    st.markdown("## 📊 ADF Error Analytics - Log Analytics")
    st.caption(
        f"Subscription: **{subscription_label.split(' (')[0]}**  ·  "
        f"Workspace: **{workspace_label.split(' · ')[0]}**  ·  Lookback: **{lookback_days} Days**"
    )
    st.markdown("---")

    analysis: Analysis = st.session_state.analysis
    if analysis is None:
        st.info(
            "👈 Configure the **Subscription**, **Log Analytics Workspace**, and **Lookback** window in "
            "the sidebar, then click **Run Analysis**. Demo Data works instantly with no sign-in; "
            "Live mode requires signing in on the Authentication tab first."
        )
        return

    df = analysis.detail_df
    if not show_raw:
        df = df.copy()
        df["Error"] = df["Error"].apply(redact_text)

    # ----------------------------------------------------------------------
    # 1-2 · Failed Pipeline Counts
    # ----------------------------------------------------------------------
    st.markdown("### 🔴 Failed Pipeline Counts")
    c1, c2, c3 = st.columns(3)
    c1.metric("Today's Failures", analysis.today_failures)
    c2.metric("Yesterday", analysis.yesterday_failures)
    c3.metric("Day-over-Day", f"{analysis.dod_delta:+d}", delta=analysis.dod_delta)

    # ----------------------------------------------------------------------
    # 3 · Resolved vs Unresolved Failures
    # ----------------------------------------------------------------------
    st.markdown("### 🔄 Resolved vs Unresolved Failures")
    c1, c2 = st.columns(2)
    c1.metric("✅ Resolved", analysis.resolved)
    c2.metric("🔴 Unresolved", analysis.unresolved)

    # ----------------------------------------------------------------------
    # 4 · Failures Carried Forward
    # ----------------------------------------------------------------------
    st.markdown("### ⏳ Failures Carried Forward")
    st.markdown(f"**Carried Forward: {len(analysis.carried_forward_df)}**")
    if len(analysis.carried_forward_df):
        st.dataframe(analysis.carried_forward_df, width='stretch', hide_index=True)
    else:
        st.success("No failures carried forward from previous days. 🎉")

    # ----------------------------------------------------------------------
    # 5 · New vs Recurring Errors
    # ----------------------------------------------------------------------
    st.markdown("### ♻️ New vs Recurring Errors")
    c1, c2 = st.columns(2)
    c1.metric("🆕 New", analysis.new_count)
    c2.metric("🔁 Recurring", analysis.recurring_count)
    st.bar_chart(analysis.new_vs_recurring_df, horizontal=True)

    # ----------------------------------------------------------------------
    # 6 · Error Trend & Anomalies
    # ----------------------------------------------------------------------
    st.markdown("### 📈 Error Trend & Anomalies")
    trend_display = analysis.daily_trend.copy()
    trend_display.index = [d.strftime("%a %m/%d") for d in trend_display.index]
    st.line_chart(trend_display)
    if analysis.anomaly_dates:
        for d in analysis.anomaly_dates:
            st.warning(f"⚠️ **Anomaly detected** on {d.strftime('%Y-%m-%d')} — failure count significantly above baseline.")
    else:
        st.success("No anomalies detected in the selected window.")

    # ----------------------------------------------------------------------
    # 7-8 · Root Cause Summary
    # ----------------------------------------------------------------------
    st.markdown("### 🎯 Root Cause Summary")
    st.dataframe(analysis.root_cause_df, width='stretch', hide_index=True)

    st.markdown("---")

    # ----------------------------------------------------------------------
    # 8b · Remediation / Resolution Plan for Recurring Failures  (LLM-generated)
    # ----------------------------------------------------------------------
    st.markdown("### 🛠️ Remediation / Resolution Plan for Recurring Failures")
    st.caption(
        "For every error that keeps coming back (same Pipeline · Activity · Root cause "
        "failing on multiple days), this builds a prioritised, step-by-step resolution plan. "
        "With an LLM provider configured, the steps are written from the **actual error text** "
        "of each failure rather than a fixed per-category template."
    )

    rc1, rc2, rc3 = st.columns([3, 2, 1])
    with rc1:
        min_days = st.slider(
            "Treat a failure as *recurring* when it appears on at least this many distinct days",
            min_value=2, max_value=7, value=2, key="remediation_min_days",
        )
    with rc2:
        ai_available = llm_enabled()
        use_llm = st.toggle(
            "🤖 AI-generated remediation steps",
            value=ai_available,
            disabled=not ai_available,
            key="remediation_use_llm",
            help=("Reads the real error text of each recurring failure and writes a grounded "
                  "playbook. Falls back to the static playbooks if a call fails."
                  if ai_available else
                  "No LLM provider configured — set LLM_PROVIDER in .streamlit/secrets.toml."),
        )
        st.caption(f"Provider: {provider_label()}")
    with rc3:
        if st.button("↻ Regenerate", width='stretch', key="remediation_regen",
                     help="Clear the AI cache and rebuild every playbook"):
            clear_cache()
            st.rerun()

    if not ai_available:
        st.info(
            "Running on **static fallback playbooks**. Add `LLM_PROVIDER` and credentials to "
            "`.streamlit/secrets.toml` to generate steps from the real error text.",
            icon="ℹ️",
        )

    with st.spinner("Building remediation plan..."):
        plan_items = build_remediation_plan(
            analysis.detail_df,
            min_days=min_days,
            use_llm=use_llm,
            platform="Azure Data Factory",
        )

    if not plan_items:
        st.success(
            f"✅ No failures recurred on {min_days}+ distinct days in this window — "
            "no resolution plan needed. 🎉"
        )
    else:
        crit = sum(1 for i in plan_items if "Critical" in i.severity)
        high = sum(1 for i in plan_items if "High" in i.severity)
        active = sum(1 for i in plan_items if i.still_active_today)
        ai_n = sum(1 for i in plan_items if i.plan_source == "llm")

        k1, k2, k3, k4 = st.columns(4)
        k1.metric("Recurring issues", len(plan_items))
        k2.metric("🔴 Critical", crit)
        k3.metric("🟠 High", high)
        k4.metric("Still failing today", active)

        st.caption(
            f"🤖 {ai_n} of {len(plan_items)} playbook(s) AI-generated from the raw error text  ·  "
            f"📘 {len(plan_items) - ai_n} using the static fallback."
        )

        st.markdown("**Prioritised plan (highest priority first):**")
        st.dataframe(plan_summary_df(plan_items), width='stretch', hide_index=True)

        st.markdown("**Step-by-step playbooks:**")
        for idx, it in enumerate(plan_items, 1):
            badge = "🤖" if it.plan_source == "llm" else "📘"
            header = (f"{badge}  {it.severity}  ·  {it.pipeline} / {it.activity}  ·  "
                      f"{it.error_category}  ·  {it.occurrences}x over {it.days_affected} day(s)")
            with st.expander(header, expanded=(idx == 1)):
                c1, c2, c3 = st.columns(3)
                c1.markdown(f"**Owner:** {it.owner}")
                c2.markdown(f"**Target date:** {it.target_date.isoformat()}")
                c3.markdown(f"**Still failing today:** {'Yes' if it.still_active_today else 'No'}")

                st.markdown(f"**First → last seen:** {it.first_seen} → {it.last_seen}")
                st.markdown(
                    f"**Root cause:** {it.root_cause}"
                    + (f"  ·  _confidence: {it.confidence}_" if it.confidence else "")
                )

                if it.sample_errors:
                    with st.popover("🔎 View the error text this plan was built from"):
                        for e in it.sample_errors:
                            st.code(e if show_raw else redact_text(e), language="text")

                st.markdown("**Remediation steps:**")
                for n, step in enumerate(it.steps, 1):
                    st.markdown(f"{n}. {step}")

                if it.validation:
                    st.success(f"**Validation:** {it.validation}", icon="✅")

                if it.preventive:
                    st.markdown("**Preventive actions (stop it recurring):**")
                    for p in it.preventive:
                        st.markdown(f"- {p}")

        dl1, dl2 = st.columns(2)
        dl1.download_button(
            "📥 Download plan (Markdown)",
            data=plan_to_markdown(plan_items, generated_for=subscription_label.split(' (')[0]).encode("utf-8"),
            file_name=f"ADF_Recurring_Remediation_Plan_{df['Date'].max()}.md",
            mime="text/markdown",
            width='stretch',
        )
        dl2.download_button(
            "📥 Download plan (CSV — one row per step)",
            data=plan_to_csv(plan_items),
            file_name=f"ADF_Recurring_Remediation_Plan_{df['Date'].max()}.csv",
            mime="text/csv",
            width='stretch',
        )

        # ------------------------------------------------------------------
        # Critical persistent-failure escalation (email + Teams)
        # The alert bodies render it.steps, so they carry the AI steps as-is.
        # ------------------------------------------------------------------
        st.markdown("#### 🚨 Escalation for Critical persistent failures")
        esc_days = st.slider(
            "Escalate when a Critical pipeline has failed on at least N days",
            min_value=3, max_value=14, value=ESCALATION_MIN_DAYS, key="esc_days",
        )
        candidates = find_escalations(plan_items, min_days=esc_days, critical_only=True)
        if not candidates:
            st.success(f"✅ No Critical failure has persisted {esc_days}+ days — nothing to escalate.")
        else:
            st.error(f"🚨 {len(candidates)} Critical issue(s) persisted {esc_days}+ days and qualify for alerting.")
            st.dataframe(
                [{"Pipeline": c.pipeline, "Activity": c.activity, "Days": c.days_affected,
                  "Root cause": c.error_category, "Owner": c.owner,
                  "Plan": "🤖 AI" if c.plan_source == "llm" else "📘 Static"} for c in candidates],
                width='stretch', hide_index=True,
            )
            teams_webhook = st.text_input(
                "Teams webhook URL", type="password", value=_secret("TEAMS_WEBHOOK", ""),
            )
            recipients = st.text_input(
                "Email recipients (comma-separated)", value=_secret("ALERT_RECIPIENTS", ""),
            ).split(",")

            colA, colB = st.columns(2)
            if colA.button("📨 Send alerts now"):
                results = dispatch_escalations(
                    plan_items, min_days=esc_days,
                    factory=subscription_label.split(' (')[0],
                    teams_webhook=teams_webhook.strip(),
                    credential=st.session_state.get("credential"),   # email via Graph (needs Mail.Send)
                    recipients=[r for r in recipients if r.strip()],
                    force=True,                                      # manual send ignores throttle
                )
                for r in results:
                    (st.success if (r.email_ok or r.teams_ok) else st.warning)(
                        f"{r.pipeline}: email={r.email_detail} · teams={r.teams_detail}")
            colB.caption("Auto-send fires once per issue per day (throttled).")

    st.markdown("---")

    # ========================================================================
    # PIPELINE & NOTEBOOK ANALYTICS (expander, 4 tabs)
    # ========================================================================
    with st.expander("📓 Pipeline & Notebook Analytics", expanded=True):
        tab_overview, tab_pipelines, tab_activities, tab_notebooks = st.tabs(
            ["📈 Overview", "⚙️ Pipelines", "🔄 Activities", "📓 Notebooks"]
        )

        with tab_overview:
            st.markdown("#### 📈 Overview Tab")
            m = analysis.overview_metrics
            c1, c2, c3, c4 = st.columns(4)
            c1.metric("Failed Runs", m["Failed Runs"])
            c2.metric("Failed Pipes", m["Failed Pipes"])
            c3.metric("Failed Actv", m["Failed Actv"])
            c4.metric("Unique Errors", m["Unique Errors"])
            st.markdown("**Top Failed Pipelines**")
            st.bar_chart(analysis.top_pipelines.head(10))
            st.markdown("**Top Failed Activities**")
            st.bar_chart(analysis.top_activities.head(10))

        with tab_pipelines:
            st.markdown("#### ⚙️ Pipelines Tab")
            st.markdown("**Pipeline Selector**")
            pipeline_options = sorted(df["PipelineName"].unique())
            selected_pipeline = st.selectbox("Select Pipeline", pipeline_options, key="pipeline_selector")
            pdf = df[df["PipelineName"] == selected_pipeline]
            st.markdown("**Metrics**")
            st.metric("Failures", len(pdf))
            st.markdown("**Detailed table:**")
            st.dataframe(
                pdf[["TimeGenerated", "ActivityName", "Status", "Error"]]
                  .rename(columns={"ActivityName": "Activity"})
                  .sort_values("TimeGenerated", ascending=False),
                width='stretch', hide_index=True,
            )
            st.markdown("**Error Distribution**")
            st.bar_chart(pdf["ErrorCategory"].value_counts())

        with tab_activities:
            st.markdown("#### 🔄 Activities Tab")
            st.markdown("**Activity Selector**")
            activity_options = sorted(df["ActivityName"].unique())
            selected_activity = st.selectbox("Select Activity", activity_options, key="activity_selector")
            adf_sel = df[df["ActivityName"] == selected_activity]
            st.markdown("**Metrics:**")
            st.metric("Failures", len(adf_sel))
            st.markdown("**Table:**")
            st.dataframe(
                adf_sel[["PipelineName", "ActivityName", "ErrorCategory"]]
                    .rename(columns={"ActivityName": "Activity", "ErrorCategory": "Error"})
                    .drop_duplicates().reset_index(drop=True),
                width='stretch', hide_index=True,
            )
            st.markdown("**Trend Chart:**")
            st.line_chart(adf_sel.groupby("Date").size().sort_index())

        with tab_notebooks:
            st.markdown("#### 📓 Notebooks Tab")
            st.caption("This is the most useful section for your Databricks demo.")
            nb_df = df[df["IsNotebook"]]
            st.markdown("**Metrics:**")
            c1, c2, c3 = st.columns(3)
            c1.metric("Notebook Runs", len(nb_df))
            c2.metric("Notebook Actv", nb_df["ActivityName"].nunique())
            c3.metric("Pipelines", nb_df["PipelineName"].nunique())
            st.markdown("**Notebook Failure Details:**")
            st.dataframe(
                nb_df[["PipelineName", "ActivityName", "ErrorCategory"]]
                    .rename(columns={"ActivityName": "Notebook", "ErrorCategory": "Error"})
                    .drop_duplicates().reset_index(drop=True),
                width='stretch', hide_index=True,
            )
            st.markdown("**Most Failing Notebook Pipelines:**")
            if len(nb_df):
                st.bar_chart(nb_df["PipelineName"].value_counts())
            else:
                st.info("No notebook activity failures found in this window.")

    st.markdown("---")

    # ========================================================================
    # 9 · AUTOMATED ALERTS & DAILY REPORT
    # ========================================================================
    st.markdown("### Automated Alerts & Daily Report")
    st.caption(f"Alert if Today's Failures >= [ {alert_threshold} ]")
    if analysis.today_failures >= alert_threshold:
        st.error(f"🚨 **ALERT** : {analysis.today_failures} failures today")
    else:
        st.success(f"✅ No alert — {analysis.today_failures} failures today (below threshold of {alert_threshold})")

    daily_report = df[df["Date"] == df["Date"].max()][
        ["TimeGenerated", "PipelineName", "ActivityName", "ActivityType", "ErrorCategory", "RecommendedAction"]
    ].rename(columns={"ErrorCategory": "Error", "RecommendedAction": "Recommended Action"})
    csv_bytes = daily_report.to_csv(index=False).encode("utf-8")
    st.download_button(
        label="📥 Download Daily Report CSV",
        data=csv_bytes,
        file_name=f"ADF_Daily_Failure_Report_{df['Date'].max()}.csv",
        mime="text/csv",
    )
